export function isAllowedIdentical(
  keyPath: string,
  english: string,
  translated: string
): boolean {
  if (english === translated) {
    if (ALLOW_IDENTICAL_KEYS.has(keyPath)) return true;
    if (ALLOW_IDENTICAL_COGNATE_KEYS.has(keyPath)) return true;
    if (PENDING_TRANSLATION_KEYS.has(keyPath)) return true;
    if (ALLOW_IDENTICAL_TOKENS.has(english.trim())) return true;
    // Pure punctuation / numerals
    if (/^[\d\s.#+\-–—/%]+$/.test(english.trim())) return true;
  }
  return false;
}

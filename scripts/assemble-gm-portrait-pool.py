#!/usr/bin/env python3
"""Assemble a fixed-size fictional photo cohort, preserving existing 50 photos.

Does not create images or bill fal. Enforces manifest IDs, QA, asset byte limits.
Artifact directories:
  .portrait-parts/portrait-shard-{0..8}/{manifest.json,v3-051.jpg,...}
"""
import json, hashlib, math
from pathlib import Path
from PIL import Image, ImageFilter, ImageDraw, ImageStat
import numpy as np

ROOT=Path(".portrait-parts")
DEST=Path("public/gm/portraits")
DEST.mkdir(parents=True,exist_ok=True)
EXPECTED_NEW=450
report={"version":2,"sourceModel":"fal-ai/flux-2","sourceRun":"same-workflow",
        "previousAssets":50,"newAssets":0,"failedGenerationIds":[],"failedQualityIds":[],
        "possibleSimilaritiesRequireHumanReview":True,"images":[]}
existing=sorted(DEST.glob("v3-??.webp"))
assert len(existing)==50, "Pilot base must be exactly 50 2-digit photo files"
assert len(list(DEST.glob("v3-??-jersey-mask.webp")))==50,"Original masks missing"
old=json.loads((DEST/"manifest.json").read_text())
if len(old["images"])!=50:raise RuntimeError("Expected preexisting 50 metadata entries")
report["images"].extend(old["images"])

for shard in range(9):
    root=ROOT/("portrait-shard-"+str(shard))
    if not (root/"manifest.json").exists():
        nested=list(root.glob("portrait-scale-*/manifest.json"))
        if len(nested)!=1:raise RuntimeError("Missing or ambiguous shard manifest: "+str(shard))
        root=nested[0].parent
    manifest=json.loads((root/"manifest.json").read_text())
    if manifest["shard"]!=shard or manifest["expected"]!=50 or manifest["model"]!="fal-ai/flux-2":
        raise ValueError("Shard mismatch")
    validids={f"v3-{i:03d}" for i in range(51+shard*50,101+shard*50)}
    ids={e["id"] for e in manifest["images"]}
    if not ids.issubset(validids) or len(ids)!=len(manifest["images"]):raise RuntimeError("Unexpected/duplicate shard IDs")
    report["failedGenerationIds"] += [x["id"] for x in manifest.get("failures",[])]
    for entry in manifest["images"]:
        id=entry["id"]
        src=root/(id+".jpg")
        if not src.exists() or src.stat().st_size<12000:
            report["failedQualityIds"].append(id);continue
        with Image.open(src) as photo:
            im=photo.convert("RGB")
        if im.size!=(960,960):
            report["failedQualityIds"].append(id);continue
        # Lightweight QA: reject blank images, abnormal sky-color top corner,
        # or missing photographic contrast. This is not a face-likeness test.
        grayStats=ImageStat.Stat(im.convert("L"))
        if grayStats.stddev[0]<15:
            report["failedQualityIds"].append(id);continue
        im=im.resize((512,512),Image.Resampling.LANCZOS)
        rgb=np.asarray(im,dtype=np.float32)
        red,green,blue=rgb[:,:,0],rgb[:,:,1],rgb[:,:,2]
        y=np.arange(512)[:,None]
        navy=(blue>red*1.20)&(blue>green*1.10)&(red<125)&(green<130)&(blue<185)
        mask=np.where(navy&(y>=286),255,0).astype("uint8")
        layer=Image.new("RGBA",(512,512),(255,255,255,0))
        layer.putalpha(Image.fromarray(mask,"L").filter(ImageFilter.GaussianBlur(.7)))
        im.save(DEST/(id+".webp"),"WEBP",quality=85,method=6)
        layer.save(DEST/(id+"-jersey-mask.webp"),"WEBP",quality=90,method=6)
        report["images"].append({
            "id":id,"portrait":id+".webp","jerseyMask":id+"-jersey-mask.webp",
            "sourceSha256":hashlib.sha256(src.read_bytes()).hexdigest(),
            "seed":entry.get("seed"),"description":entry.get("description")})
        report["newAssets"]+=1

assert len({x["id"] for x in report["images"]})==len(report["images"]),"Duplicate photo IDs"
assert len(report["images"])>=470, "Too few usable photos for a 500-player beta: review failures before deployment"
ids=[x["id"] for x in report["images"]]
catalog='''/**
 * GENERATED by scripts/assemble-gm-portrait-pool.py — do not edit by hand.
 * Local, immutable vetted candidate photo IDs available in public/gm/portraits.
 */
export const GM_PHOTO_POOL_CATALOG = '''+json.dumps(ids,indent=2)+''' as const;
'''
Path("src/gm/lib/generated-photo-pool-catalog.ts").write_text(catalog)
(DEST/"manifest.json").write_text(json.dumps(report,indent=2)+"\n")
# A lightweight contact sheet of *new* assets for inspection.
newIds=ids[50:]
cols=10; thumb=110; h=132
sheet=Image.new("RGB",(cols*thumb,math.ceil(len(newIds)/cols)*h),(18,24,34))
draw=ImageDraw.Draw(sheet)
for index,id in enumerate(newIds):
    with Image.open(DEST/(id+".webp")) as image:
        face=image.convert("RGB").resize((thumb,thumb))
    x=(index%cols)*thumb;y=(index//cols)*h
    sheet.paste(face,(x,y));draw.text((x+4,y+112),id,fill=(240,242,245))
sheet.save(DEST/"review-contact.jpg",quality=86,optimize=True)
print(json.dumps({"totalPhotos":len(ids),"newPhotos":report["newAssets"],
                  "generationFailures":len(report["failedGenerationIds"]),
                  "qualityFailures":len(report["failedQualityIds"]),
                  "bundleBytes":sum(x.stat().st_size for x in DEST.iterdir() if x.is_file())},indent=2))

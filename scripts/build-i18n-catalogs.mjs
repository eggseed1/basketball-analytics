function flatKeys(obj, prefix = "") {
  const keys = [];
  for (const [k, v] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) keys.push(...flatKeys(v, path));
    else keys.push(path);
  }
  return keys;
}

const en = JSON.parse(fs.readFileSync("messages/en.json", "utf8"));
const enKeys = new Set(flatKeys(en));

for (const [code, data] of Object.entries(all)) {
  const keys = flatKeys(data);
  const missing = [...enKeys].filter((k) => !keys.includes(k));
  const extra = keys.filter((k) => !enKeys.has(k));
  if (missing.length || extra.length) {
    console.error(code, "missing", missing.length, "extra", extra.length);
    if (missing.length) console.error(missing.slice(0, 10));
  }
  fs.writeFileSync(`messages/${code}.json`, JSON.stringify(data, null, 2) + "\n");
  console.log("wrote", code, keys.length, "keys");
}


function deepMerge(base, overlay) {
  const out = { ...base };
  for (const [k, v] of Object.entries(overlay)) {
    const prev = out[k];
    if (
      v &&
      typeof v === "object" &&
      !Array.isArray(v) &&
      prev &&
      typeof prev === "object" &&
      !Array.isArray(prev)
    ) {
      out[k] = deepMerge(prev, v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

function flatKeys(obj, prefix = "") {
  const keys = [];
  for (const [k, v] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) keys.push(...flatKeys(v, path));
    else keys.push(path);
  }
  return keys;
}

function pseudo(value) {
  if (typeof value !== "string") return value;
  // Keep ICU placeholders readable: wrap around {name} segments.
  return value.replace(/\{[^}]+\}|[^{]+/g, (chunk) => {
    if (chunk.startsWith("{")) return chunk;
    return `【${chunk}】 ···`;
  });
}

function mapTree(obj, fn) {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    out[k] = v && typeof v === "object" && !Array.isArray(v) ? mapTree(v, fn) : fn(v);
  }
  return out;
}

